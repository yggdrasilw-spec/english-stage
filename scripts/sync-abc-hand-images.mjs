import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
const root=new URL('../dist/',import.meta.url),check=process.argv.includes('--check');
const read=async name=>(await readFile(new URL(name,root),'utf8')).replace(/\r\n/g,'\n');
const hunter=await read('hunter-data.js'),cards=JSON.parse(await read('data/grade5.json'));
const {D,audioFiles}=vm.runInNewContext(hunter+';({D,audioFiles})');
const norm=s=>s.trim().toLowerCase(),byEnglish=new Map();
for(const c of cards){const key=norm(c.en);if(!byEnglish.has(key))byEnglish.set(key,[]);byEnglish.get(key).push(c);}
const extra=JSON.parse(await readFile(new URL('../scripts/game-image-links.json',root),'utf8'));
const imageHints=[];
const images=D.map((d,i)=>{
 const candidates=byEnglish.get(norm(d[0]))||[];
 const audio=candidates.filter(c=>audioFiles[i].startsWith(c.id+'-word-'));
 const exact=candidates.filter(c=>c.ja===d[2]);
 const card=audio.length===1?audio[0]:exact.length===1?exact[0]:candidates.length===1?candidates[0]:null;
 imageHints[i]=!!card&&!['g5-w-tooth','g5-w-teeth'].includes(card.id)&&!!card.image&&(/diagram|assets\/vocabulary\/g5-|図/.test(card.image.url+' '+(card.image.sourceSheet||'')+' '+(card.image.credit||'')));
 return card?.image?.url||extra[i]?.url||d[3]||null;
});
const output='// Generated by scripts/sync-abc-hand-images.mjs from current reviewed card images.\nconst abcHandImages='+JSON.stringify(images)+';\nconst abcHandImageHints='+JSON.stringify(imageHints)+';\n';
const digest=createHash('sha256').update(output).digest('hex').slice(0,16),tag=`<script src="abc-hand-images.js?v=${digest}"></script>`;
const engineHash=createHash('sha256').update(await read('abc-hand-engine.js')).digest('hex').slice(0,16);
const html=await read('abc-hand.html'),next=html.replace(/<script src="abc-hand-images\.js\?v=[^"]+"><\/script>/,tag).replace(/abc-hand-engine\.js\?v=[^"]+/,`abc-hand-engine.js?v=${engineHash}`);
if(next===html&&!html.includes(tag))throw Error('ABC HAND image script tag is missing');
if(check){if(await read('abc-hand-images.js')!==output||next!==html)throw Error('ABC HAND image map is stale: node scripts/sync-abc-hand-images.mjs');}
else{await writeFile(new URL('abc-hand-images.js',root),output);await writeFile(new URL('abc-hand.html',root),next);}
const hunterURL=new URL('hunter.html',root),hunterHTML=(await readFile(hunterURL,'utf8')).replace(/\r\n/g,'\n'),hunterNext=hunterHTML.replace(/<script src="abc-hand-images\.js\?v=[^"]+"><\/script>/,tag);if(check){if(hunterNext!==hunterHTML)throw Error('Hunter shared image map is stale');}else await writeFile(hunterURL,hunterNext);
console.log(`PASS ABC HAND current reviewed images: ${images.filter(Boolean).length}/${D.length}`);
