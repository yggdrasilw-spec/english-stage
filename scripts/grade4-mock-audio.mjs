import {readFile, rename, writeFile} from 'node:fs/promises';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {buildExamAudio} from './exam-audio-plan.mjs';
import {listeningPractice, mockListening} from '../dist/src/grade4-mock-listening.js';

const dist = new URL('../dist/', import.meta.url);
const jobs = [...listeningPractice, ...mockListening].map(question => {
  const {body, path} = buildExamAudio(question);
  return {id:question.id, body, path};
});
const pending = [];
for (const job of jobs) {
  const existing = await readFile(new URL(job.path, dist)).catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (!existing || existing.length <= 100) pending.push(job);
}
const characters = pending.reduce((total, job) => total + [...job.body.input.ssml].length, 0);
if (characters > 20000) throw Error('SSML character budget exceeded');
console.log(JSON.stringify({files:jobs.length, pending:pending.length, characters}));
if (!process.argv.includes('--generate')) process.exit(0);

let index = 0;
let sentCharacters = 0;
if (pending.length) {
  const {stdout} = await promisify(execFile)('powershell.exe', ['-NoProfile', '-Command', 'gcloud.cmd auth print-access-token'], {windowsHide:true});
  const headers = {
    Authorization:'Bearer ' + stdout.trim(),
    'x-goog-user-project':'tts-test-513311',
    'Content-Type':'application/json'
  };
  async function worker() {
    while (index < pending.length) {
      const job = pending[index++];
      sentCharacters += [...job.body.input.ssml].length;
      const response = await fetch('https://texttospeech.googleapis.com/v1/text:synthesize', {
        method:'POST', headers, body:JSON.stringify(job.body)
      });
      if (!response.ok) throw Error(job.id + ': TTS HTTP ' + response.status);
      const {audioContent} = await response.json();
      if (!audioContent) throw Error(job.id + ': no audio');
      const temporary = new URL(job.path + '.tmp', dist);
      await writeFile(temporary, Buffer.from(audioContent, 'base64'));
      await rename(temporary, new URL(job.path, dist));
      console.log('Created ' + job.id);
    }
  }
  const results = await Promise.allSettled([worker(), worker(), worker()]);
  console.log(JSON.stringify({sentCharacters}));
  const failed = results.find(result => result.status === 'rejected');
  if (failed) throw failed.reason;
}
const files = Object.fromEntries(jobs.map(({id, path}) => [id, path]));
await writeFile(new URL('src/grade4-mock-audio.js', dist),
  '// Generated by scripts/grade4-mock-audio.mjs.\nexport const audioFiles = ' + JSON.stringify(files, null, 2) + ';\n');
