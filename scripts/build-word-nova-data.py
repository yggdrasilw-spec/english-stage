from pathlib import Path
import json,re
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'dist'
cards=json.loads((ROOT/'dist/data/grade5.json').read_text(encoding='utf-8'))
manifest=json.loads((ROOT/'dist/data/audio-manifest.json').read_text(encoding='utf-8'))['files']
audio={};audio_id={}
for f in manifest:
    if f['part']=='word' and f['speed']=='normal':
        audio.setdefault(f['text'].strip().lower(),f['path']);audio_id.setdefault(f['id'],f['path'])
words=[];seen=set();cats={}
for c in cards:
    key=c['en'].strip().lower()
    if c['kind']!='word' or key in seen or c['id'] not in audio_id: continue
    seen.add(key);cat='theme'+str(list(cats).index(c['theme']) if c['theme'] in cats else len(cats));cats[c['theme']]=cat
    words.append(dict(id=c['en'],en=c['en'],ja=c['ja'],cat=cat,audio=audio_id[c['id']]))
groups=[['cap','cup'],['cat','cut'],['bed','bad'],['pig','big'],['ship','sheep'],['hat','hot'],['bag','big'],['pen','ten'],['rice','right'],['ear','year'],['mouth','mouse'],['sing','thing'],['three','tree'],['boat','coat'],['cold','called'],['fifteen','fifty'],['thirteen','thirty'],['fourteen','forty'],['sixteen','sixty'],['seventeen','seventy'],['eighteen','eighty'],['nineteen','ninety'],['ball','bowl']]
groups=[[x for x in g if x in seen] for g in groups];groups=[g for g in groups if len(g)>1]
near={x for g in groups for x in g}
# Keep the original near-word category; use explicit sound pairs rather than spelling distance alone.
for w in words:
    if w['en'].lower() in near:w['cat']='near'
data=dict(words=words,categories={v:k for k,v in cats.items()}|{'near':'にたことば'},groups=groups)
(OUT/'word-nova-data.js').write_text('/* Existing Grade 5 vocabulary and MP3 paths. Generated by scripts/build-word-nova.py. */\nwindow.WORD_NOVA_DATA='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
