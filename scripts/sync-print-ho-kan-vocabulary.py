"""Apply reviewed PDF coverage, independent cards, and portable priority metadata."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def read(path):return json.loads((ROOT/path).read_text(encoding='utf-8'))
def write(path,value):
 (ROOT/path).write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
def sync():
 cards=read('dist/data/grade5.json');extra=read('scripts/grade5-expansion-04.json');by={c['id']:c for c in cards}
 for c in extra:
  if c['id'] in by:
   assert {k:v for k,v in by[c['id']].items() if k!='image'}=={k:v for k,v in c.items() if k!='image'},c['id']+' content changed'
  else:
   assert not any(old['en'].casefold()==c['en'].casefold() for old in cards),c['en']
   cards.append(c)
 write('dist/data/grade5.json',cards)
 write('AUDIO_SCRIPT.json',[{'id':c['id'],'word':c['audioText'],'example':c['example']} for c in cards])
 coverage=read('scripts/print-ho-kan-coverage.json');priority={}
 for row in coverage['entries']:
  for id in row['itemIds']:
   assert any(c['id']==id for c in cards),id
   candidate={'rank':row['rank'],'page':row['page'],'number':row['number']}
   if id not in priority or (candidate['rank'],candidate['page'],candidate['number'])<(priority[id]['rank'],priority[id]['page'],priority[id]['number']):priority[id]=candidate
 (ROOT/'dist/src/vocabulary-priority-data.js').write_text('// Generated by scripts/sync-print-ho-kan-vocabulary.py; do not infer official exam frequency.\nexport const priorityData = '+json.dumps(priority,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
 import runpy
 runpy.run_path(str(ROOT/'scripts/sync-shiritori-images.py'))['sync']()
 print(f'PDF vocabulary: {len(extra)} new items; {len(cards)} total; {len(coverage["entries"])} source rows covered')
if __name__=='__main__':sync()
